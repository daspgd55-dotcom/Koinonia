const assert = require('node:assert/strict');
const path = require('node:path'), fs = require('node:fs/promises');
const { createRequire } = require('node:module');
const backend = createRequire(path.resolve(__dirname, '../../Backend/package.json'));
const { chromium } = backend('playwright');
const { MongoMemoryServer } = backend('mongodb-memory-server');
const { connectDB, disconnectDB } = backend('./src/config/db');
const { createApp } = backend('./src/app');
const User = backend('./src/models/user.model');
let mongo, server, vite, browser;
const output = path.resolve(__dirname, '../.cache/journey');
async function main() {
  await fs.mkdir(output,{recursive:true});
  mongo = await MongoMemoryServer.create({ binary:{version:'8.0.12',downloadDir:path.resolve(__dirname,'../../Backend/.cache/mongodb')} });
  await connectDB(mongo.getUri('koinonia_web_test'));
  server = createApp({jwtSecret:'web-test-only-secret-longer-than-32-characters',corsOrigins:[],enableTestUi:false}).listen(0,'127.0.0.1');
  await new Promise(resolve => server.once('listening',resolve));
  const { createServer } = await import('vite');
  vite = await createServer({ root:path.resolve(__dirname,'..'),configFile:false,server:{host:'127.0.0.1',port:0,proxy:{'/api':`http://127.0.0.1:${server.address().port}`}} });
  await vite.listen(); const url = `http://127.0.0.1:${vite.httpServer.address().port}`;
  browser = await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'msedge'}:{})});
  const context = await browser.newContext({viewport:{width:1440,height:1000}}), page = await context.newPage(), errors=[];
  page.on('pageerror',e=>errors.push(e.message)); page.setDefaultTimeout(12000);

  const Church=backend('./src/models/church.model'), mongoose=backend('mongoose');
  await Church.create(Array.from({length:14},(_,i)=>({identification:{name:`Comunidad ${String(i+1).padStart(2,'0')}`},verification:{source:'PRIVATE-ORIGIN'},media:[1,2,3,4,5].map(n=>({type:'image',url:'https://images.example.test/'+n+'.png',title:'Imagen '+n})),location:{commune:i===0?'Providencia':'Santiago',coordinates:{type:'Point',coordinates:[-70.65+i*.001,-33.45]}},christianIdentity:{branch:'Protestante',denomination:i===0?'Metodista':'Bautista'},meetings:[{type:'Culto',schedule:[{day:'Domingo',startTime:'11:00'}]}],community:{activities:['Voluntariado']},metadata:{dataStatus:'published',testData:true},createdBy:new mongoose.Types.ObjectId()})));
  await Church.init();
  await page.route('https://tile.openstreetmap.org/**',r=>r.abort());
  await page.route('https://images.example.test/**',r=>r.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="800" height="500"><rect width="800" height="500" fill="teal"/></svg>'}));
  await page.goto(url+'/#/explorar');
  await page.getByRole('status').filter({hasText:'14 comunidades encontradas'}).waitFor();
  assert.equal(await page.locator('.church-card').count(),12);
  await page.getByRole('button',{name:'Siguiente',exact:true}).click();
  await page.getByText('Página 2 de 2',{exact:true}).waitFor();
  assert.equal(await page.locator('.church-card').count(),2);
  await page.getByLabel('Comuna',{exact:true}).fill('Providencia');
  await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click();
  await page.getByRole('status').filter({hasText:'1 comunidades encontradas'}).waitFor();
  await page.getByRole('link',{name:'Ver comunidad Comunidad 01'}).click();
  await page.getByRole('heading',{name:'Comunidad 01',exact:true}).waitFor();
  await page.getByText('Domingo 11:00',{exact:true}).waitFor();
  assert.equal(await page.getByText('PRIVATE-ORIGIN').count(),0);
  await page.mouse.move(0,0);
  await page.waitForTimeout(5200);
  assert.equal(await page.getByRole('button',{name:'Ver foto 2',exact:true}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'Ampliar foto',exact:true}).click();
  await page.getByRole('dialog',{name:'Foto ampliada',exact:true}).waitFor();
  await page.getByLabel('Zoom de foto',{exact:true}).fill('2');
  assert.equal(await page.locator('.photo-zoom-scroll').evaluate(el=>el.scrollWidth>el.clientWidth),true);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Ver foto 3',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Ver foto 3',exact:true}).getAttribute('aria-pressed'),'true');
  await page.screenshot({path:path.join(output,'detail-gallery-desktop.png'),fullPage:true});

  await page.getByRole('link',{name:'Volver a resultados'}).click();
  assert.equal(await page.getByLabel('Comuna',{exact:true}).inputValue(),'Providencia');
  assert.equal(await page.locator('.church-card').count(),1);
  await page.getByRole('button',{name:'Limpiar búsqueda y filtros'}).click();
  await page.getByRole('status').filter({hasText:'14 comunidades encontradas'}).waitFor();
  await page.evaluate(()=>Object.defineProperty(navigator,'geolocation',{configurable:true,value:{getCurrentPosition:(success,error)=>error({code:1})}}));
  await page.getByRole('button',{name:'Usar mi ubicación'}).click();
  await page.getByRole('alert').filter({hasText:'No pudimos obtener'}).waitFor();
  await page.evaluate(()=>Object.defineProperty(navigator,'geolocation',{configurable:true,value:{getCurrentPosition:success=>success({coords:{latitude:-33.45,longitude:-70.65}})}}));
  await page.getByRole('button',{name:'Usar mi ubicación'}).click();
  await page.getByRole('slider').fill('2');
  await page.getByRole('button',{name:'Aplicar filtros'}).click();
  await page.getByText('A 0.0 km en línea recta',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Mapa',exact:true}).click();
  await page.locator('.leaflet-marker-icon').first().waitFor();
  assert.equal(await page.locator('.leaflet-marker-icon').count(),12);
  await page.getByRole('alert').filter({hasText:'El fondo del mapa'}).waitFor();
  await page.getByRole('button',{name:'Lista',exact:true}).click();
  await page.screenshot({path:path.join(output,'05-explore-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'06-explore-mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.getByRole('link',{name:'Ver comunidad Comunidad 01'}).click();
  await page.getByRole('heading',{name:'Comunidad 01',exact:true}).waitFor();
  await page.screenshot({path:path.join(output,'07-detail-mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.getByRole('link',{name:'Volver a resultados'}).click();
  await page.getByLabel('Nombre de iglesia o comunidad').fill('Sin coincidencias');
  await page.getByRole('button',{name:'Buscar comunidades'}).click();
  await page.getByRole('heading',{name:'No encontramos coincidencias'}).waitFor();
  await page.route('**/api/churches/search?**',r=>r.abort());
  await page.getByRole('button',{name:'Ver todas las comunidades'}).click();
  await page.getByRole('button',{name:'Reintentar búsqueda'}).waitFor();
  await page.unroute('**/api/churches/search?**');
  await page.getByRole('button',{name:'Reintentar búsqueda'}).click();
  await page.getByRole('status').filter({hasText:'14 comunidades encontradas'}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('EXPLORAR OK: API real aislada, filtros, paginación, ficha, vuelta con contexto, GPS permitido/denegado, mapa sin red, vacío, reintento y móvil.');
}

main().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();if(vite)await vite.close();if(server){server.closeAllConnections();await new Promise(r=>server.close(r));}await disconnectDB();if(mongo)await mongo.stop();});
