// Prueba de navegador con base efímera. Nunca usa MONGO_URI ni las cuentas del usuario.
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { chromium } = require('playwright');
const { MongoMemoryServer } = require('mongodb-memory-server');
const bcrypt = require('bcryptjs');
const { createApp } = require('../src/app');
const { connectDB, disconnectDB } = require('../src/config/db');
const Church = require('../src/models/church.model'), User = require('../src/models/user.model');
let mongo, server, browser;
const output = path.resolve(__dirname, '../.cache/ui-check');
async function main() {
  await fs.mkdir(output, { recursive: true });
  mongo = await MongoMemoryServer.create({ binary: { version: '8.0.12', downloadDir: path.resolve(__dirname, '../.cache/mongodb') } });
  await connectDB(mongo.getUri('koinonia_ui_test'));
  const admin = await User.create({ email: 'admin-ui@example.test', password: await bcrypt.hash('Test-browser-password-123', 4), role: 'admin' });
  for (let i = 1; i <= 12; i++) await Church.create({ identification: { name: 'Comunidad de prueba ' + String(i).padStart(2, '0') },
    location: { commune: i % 2 ? 'Santiago' : 'Providencia', coordinates: { type: 'Point', coordinates: [-70.65 + i / 10000, -33.45] } },
    metadata: { dataStatus: 'published', testData: true }, createdBy: admin._id, representatives: [admin._id] });
  const app = createApp({requireVerifiedEmail:false, jwtSecret: 'test-ui-only-secret-over-32-characters', corsOrigins: [], enableTestUi: true });
  server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = 'http://127.0.0.1:' + server.address().port;
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : process.platform === 'win32' ? { channel: 'msedge' } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(10000);
  await page.goto(base + '/testing/');
  await page.waitForFunction(() => document.querySelector('#result-count').textContent.includes('12 comunidades'));
  assert.equal(await page.locator('#manage-mode').isDisabled(), true);
  await page.getByRole('button', { name: 'Ver ficha', exact: true }).first().click();
  await page.waitForFunction(() => document.querySelector('#editor').open);
  assert.equal(await page.locator('#readonly-hint').isVisible(), true);
  assert.equal(await page.locator('[data-path="identification.name"]').isDisabled(), true);
  await page.locator('#close-editor').click();
  await page.locator('#next').click(); await page.waitForFunction(() => document.querySelector('#page-label').textContent === 'Página 2 de 2');
  await page.locator('#email').fill('admin-ui@example.test'); await page.locator('#password').fill('Test-browser-password-123');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#identity').textContent.includes('Administrador') && !document.querySelector('#new-church').disabled);
  await page.screenshot({ path: path.join(output, 'desktop-list.png'), fullPage: true });
  await page.locator('#manage-mode').click();
  await page.getByRole('button', { name: 'Gestionar', exact: true }).first().click();
  await page.waitForFunction(() => document.querySelector('#editor').open);
  assert.equal(await page.locator('#readonly-hint').isVisible(), false);
  assert.equal(await page.locator('[data-path="identification.name"]').isDisabled(), false);
  await page.locator('#close-editor').click();
  await page.locator('#new-church').click();
  await page.locator('[data-path="identification.name"]').fill('Prueba CRUD desde navegador');
  await page.locator('[data-path="location.commune"]').fill('Santiago');
  await page.locator('#church-lat').fill('-33.45'); await page.locator('#church-lng').fill('-70.65');
  await page.locator('#save-church').click();
  await page.waitForFunction(() => document.querySelector('#editor-notice').textContent.includes('creada correctamente'));
  let created = await Church.findOne({ 'identification.name': 'Prueba CRUD desde navegador' });
  assert.ok(created); assert.equal(created.metadata.dataStatus, 'draft');
  await page.locator('#publish-church').click(); await page.locator('#confirm-action').click();
  await page.waitForFunction(() => document.querySelector('#editor-notice').textContent.includes('Faltan datos esenciales'));
  await page.locator('[data-path="location.address"]').fill('Dirección ficticia 123');
  await page.locator('[data-path="christianIdentity.denomination"]').fill('Bautista');
  await page.locator('[data-path="doctrine.officialStatement"]').fill('Declaración de prueba para validar el flujo.');
  await page.locator('[data-path="leadership.mainLeader.name"]').fill('Responsable ficticio');
  await page.locator('[data-path="leadership.mainLeader.role"]').fill('Representante');
  await page.locator('[data-path="verification.source"]').fill('Prueba automatizada');
  await page.locator('#authorized').check(); await page.locator('#sample-meeting').click();
  await page.locator('.advanced > summary').click();
  const advanced = JSON.parse(await page.locator('#advanced-json').inputValue());
  advanced.firstVisit = { instructions: 'Este campo debe conservarse al editar el nombre.' };
  await page.locator('#advanced-json').fill(JSON.stringify(advanced)); await page.locator('#apply-json').click();
  await page.locator('#save-church').click();
  await page.waitForFunction(() => document.querySelector('#editor-notice').textContent.includes('Cambios guardados'));
  await page.locator('[data-path="identification.name"]').fill('Prueba CRUD editada'); await page.locator('#save-church').click();
  await page.waitForFunction(() => document.querySelector('#editor-title').textContent === 'Prueba CRUD editada');
  created = await Church.findById(created._id); assert.match(created.firstVisit.instructions, /conservarse/);
  await page.locator('#publish-church').click(); await page.locator('#confirm-action').click();
  await page.waitForFunction(() => document.querySelector('#editor-notice').textContent.includes('Estado actualizado: Publicada'));
  assert.equal((await Church.findById(created.id)).metadata.dataStatus, 'published');
  await page.locator('#verify-church').click(); await page.locator('#confirm-action').click();
  await page.waitForFunction(() => document.querySelector('#editor-notice').textContent.includes('Estado actualizado: Verificada'));
  await page.locator('#editor').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: path.join(output, 'desktop-editor.png'), fullPage: true });
  await page.locator('#deactivate-church').click(); await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  assert.equal((await Church.findById(created.id)).active, true);
  await page.locator('#deactivate-church').click(); await page.locator('#confirm-action').click();
  await page.waitForFunction(() => document.querySelector('#editor-notice').textContent.includes('Comunidad desactivada'));
  assert.equal((await Church.findById(created.id)).active, false);
  await page.locator('#restore-church').click(); await page.locator('#confirm-action').click();
  await page.waitForFunction(() => document.querySelector('#editor-notice').textContent.includes('restaurada como borrador'));
  assert.equal((await Church.findById(created.id)).metadata.dataStatus, 'draft');
  // Simula una segunda sesión que cambia el registro mientras el formulario conserva la versión anterior.
  const otherEdit = await Church.findById(created.id); otherEdit.identification.name = 'Cambio de otra sesión'; otherEdit.metadata.version += 1; await otherEdit.save();
  await page.locator('[data-path="identification.name"]').fill('Cambio desactualizado'); await page.locator('#save-church').click();
  await page.waitForFunction(() => document.querySelector('#editor-notice').textContent.includes('otra sesión'));
  assert.equal((await Church.findById(created.id)).identification.name, 'Cambio de otra sesión');
  await page.locator('#reload-church').click(); await page.locator('#confirm-action').click();
  await page.waitForFunction(() => document.querySelector('#editor-title').textContent === 'Cambio de otra sesión');
  await page.locator('#close-editor').click();
  await page.locator('#search-form [name="q"]').fill('Cambio de otra sesión'); await page.getByRole('button', { name: 'Buscar', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#result-count').textContent.includes('1 comunidades'));
  const log = await page.locator('#request-log').textContent();
  assert.ok(!log.includes('Test-browser-password-123')); assert.ok(!log.includes('eyJhbGci'));
  assert.equal(await page.evaluate(() => localStorage.length), 0);
  await page.locator('#logout').click(); await page.waitForFunction(() => !document.querySelector('#login-form').hidden);
  await page.locator('#reset-search').click();
  await page.waitForFunction(() => document.querySelector('#result-count').textContent.includes('12 comunidades'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('UI OK: consulta, paginación, login, creación, validación, edición, JSON, publicación, verificación, desactivación, restauración, concurrencia, filtros, sesión y móvil.');
  console.log('Capturas: .cache/ui-check/');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
  await disconnectDB(); if (mongo) await mongo.stop();
});
