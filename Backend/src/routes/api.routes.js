const router = require('express').Router();
const { auth, roles } = require('../middleware/auth.middleware');
const authController = require('../controllers/auth.controller');
const user = require('../controllers/user.controller'), church = require('../controllers/church.controller');
const interaction = require('../controllers/interaction.controller'), source = require('../controllers/source.controller');
const managers = roles('representative', 'admin'), admin = roles('admin');
const media = require('../controllers/media.controller');
router.post('/churches/:id/media', auth, managers, media.limit, media.authorize, require('express').raw({ type: ['image/jpeg', 'image/png', 'image/webp'], limit: '5mb' }), media.upload);
router.delete('/churches/:id/media/:index', auth, managers, media.authorize, media.remove);

router.post('/auth/register', authController.register);
router.post('/auth/login', authController.login);
const passwords = require('../controllers/password.controller');
router.post('/auth/forgot-password', passwords.forgot);
router.post('/auth/reset-password', passwords.reset);
router.post('/auth/change-password', auth, passwords.change);
router.get('/users/me', auth, user.profile);
router.patch('/users/me', auth, user.updateProfile);
router.put('/users/me/preferences', auth, user.preferences);
router.get('/users/manage', auth, admin, user.listManaged);
router.patch('/users/manage/:id', auth, admin, user.updateManaged);
router.get('/users/lookup', auth, admin, user.lookup);
router.post('/users/:id/promote-representative', auth, admin, user.promoteRepresentative);
router.patch('/users/:id/role', auth, admin, user.role);
router.post('/representatives', auth, admin, church.createRepresentative);
router.get('/representatives', auth, admin, church.eligibleRepresentatives);
router.get('/churches/manage', auth, managers, church.mine);
router.get('/churches/manage/:id', auth, managers, church.detail);
router.get('/churches/search', church.list);
router.get('/churches/nearby', church.list);
router.get('/churches', church.list);
router.post('/churches', auth, admin, church.create);
router.get('/churches/:id/sources', source.list);
router.post('/churches/:id/sources', auth, managers, source.create);
router.patch('/churches/:id/status', auth, admin, church.status);
router.put('/churches/:id/representatives', auth, admin, church.representatives);
router.get('/churches/:id', church.get);
router.put('/churches/:id', auth, managers, church.update);
router.delete('/churches/:id', auth, admin, church.remove);
router.post('/churches/:id/restore', auth, admin, church.restore);
router.get('/sources/pending', auth, admin, source.pending);
router.patch('/sources/:sourceId/status', auth, admin, source.status);
router.post('/interactions', auth, interaction.set);
router.get('/users/me/interactions', auth, interaction.list);
router.delete('/interactions/:churchId', auth, interaction.remove);
router.get('/recommendations/capabilities', (req, res) => res.json({ traditional: true, semantic: false, semanticStatus: 'not_implemented' }));
router.post('/recommendations', auth, require('../controllers/recommendation.controller').recommend);

module.exports = router;
